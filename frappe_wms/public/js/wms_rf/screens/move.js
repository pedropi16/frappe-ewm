// System Guided / Manual, same split as Picking/Putaway/Count: System Guided pulls an already-
// open Internal Move task (generated by Slotting's rearrangement engine, services/slotting.py) off
// a queue; Manual is this screen's own ad-hoc instant move, unchanged - there's no "find" step
// because create_and_confirm_move creates and confirms in one action, with no planning stage to
// wait on, so it was never a list to browse in the first place.
export const moveMenu = {
  id: "move", pattern: "move",
  title: () => _("Move"), crumb: () => sectionCrumb("internal"), parent: () => sectionHash("internal"),
  render: () => MenuGrid([
    { icon: "⚡", label: _("System Guided - get next task"), run: () => pullWorkAndOpen("#/tasks/internal") },
    { icon: "↔️", label: _("Manual - move now"), run: () => nav.go("#/move-manual") },
  ]),
};

// Ad-hoc move: scan the product, enter a quantity, scan the source, scan the destination, confirm. Same step-per-history-entry
// and saved-draft behaviour as the task wizard. The product and bins are scanned/resolved, never free-typed.
const STEPS = ["item", "quantity", "source", "destination", "review"];
const KEY = "move";
const blank = () => ({ product: "", product_name: "", stock_uom: "", stock_type: "AVAILABLE", quantity: "", source_bin: "", source_hu: "", source_check: "", source_checked: false, destination_bin: "", destination_hu: "", destination_check: "", destination_checked: false, idem: "", w0: nav.depth });
const st = { form: blank(), stockTypes: null, resumed: false };

// `step` is where the draft should resume: persisting just before navigating means the NEXT step, not the current one.
const persist = (immediate, step) => { saveDraft(KEY, st.form, { label: `${_("Move")} · ${st.form.product || ""}`, route: href("move-manual", step || currentStep()) }); if (immediate) flushDrafts(); };
const currentStep = () => (S.route && S.route.params.step) || "item";
const labels = () => ({ item: _("Scan product"), quantity: _("Quantity"), source: _("Scan source"), destination: _("Scan destination"), review: _("Review & move") });

function done(step, f) {
  return {
    item: !!f.product && !!f.stock_uom,
    quantity: parseNum(f.quantity) > 0,
    // A pure-bin source/destination must also clear check digits when the setting requires them -
    // same anti-cheat guarantee the generic task wizard (task.js) already applies, closing the gap
    // where an ad-hoc move could type a bin it never stood at.
    source: !!(f.source_bin || f.source_hu) && (!needsCheckDigits(f.source_bin, f.source_hu) || f.source_checked),
    destination: !!f.destination_bin && (!needsCheckDigits(f.destination_bin, f.destination_hu) || f.destination_checked),
    review: false,
  }[step];
}

async function resolve(value, want) {
  const r = await api("frappe_wms.api.scanner.resolve_scan", { code: value }, { read: true, timeoutMs: 8000 });
  return (r.matches || []).find((m) => m.type === want) || { other: (r.matches || [])[0] };
}
const KIND = () => ({ bin: _("a bin"), hu: _("a Handling Unit"), item: _("a product") });
const wrong = (v, m, want) => (m.other ? _("That is {0} ({1}), not {2}.", [KIND()[m.other.type], m.other.name, want]) : _("{0} is not a known code.", [v]));

function go(step) { persist(true, step); nav.go(href("move-manual", step)); }

export const moveManual = {
  id: "move-manual", pattern: "move-manual/:step?",
  title: () => _("Move"), crumb: () => sectionCrumb("internal"), parent: () => "#/move",
  async enter(ctx) {
    if (ctx.meta.initial || !st.resumed) { const d = loadDraft(KEY); st.form = d || blank(); st.resumed = true; if (d) st.fromDraft = !!d.product; }
    if (!st.stockTypes) {
      const rows = await load(() => api("frappe.client.get_list", { doctype: "WMS Stock Type", fields: ["name"], limit_page_length: 50 }, { read: true }));
      st.stockTypes = rows && rows.length ? rows.map((r) => r.name) : ["AVAILABLE"];
    }
    const step = ctx.params.step;
    const guard = guardStep(STEPS, step, (s) => done(s, st.form), (s) => href("move-manual", s));
    if (guard) return guard;
    if (!ctx.meta.popped && !(S.prevRoute && S.prevRoute.id === "move-manual")) st.form.w0 = nav.depth;
    update();
  },
  render(ctx) {
    const f = st.form, step = ctx.params.step || "item", idx = STEPS.indexOf(step);
    const wrap = h("div");
    if (st.fromDraft && step === "item") { wrap.append(h("div.notice.info", { style: { borderRadius: "10px", marginBottom: "12px" } }, h("span.notice-text", _("Resumed your unfinished move.")), h("button.notice-btn", { onclick: () => { clearDraft(KEY); st.form = blank(); st.fromDraft = false; update(); } }, _("Start over")))); }
    wrap.append(Stepper(STEPS.length, Math.max(0, idx), STEPS.map((s) => labels()[s])));
    const box = Section({});
    if (step === "item") {
      box.append(Field({ name: "product", kind: "scan", label: _("Product barcode or code"), placeholder: _("Scan the item"), value: f.product, autofocus: true,
        hint: f.product_name ? `${f.product} · ${f.product_name} (${f.stock_uom})` : null,
        onInput: (v) => { if (v !== f.product) { f.product = ""; f.stock_uom = ""; } persist(); },
        onCommit: async (v) => {
          const m = await resolve(v, "item");
          if (!m.name) return wrong(v, m, _("a product"));
          Object.assign(f, { product: m.name, product_name: m.item_name || "", stock_uom: m.stock_uom || "" });
          if (!f.stock_uom) return _("That item has no unit of measure.");
          go("quantity");
        } }),
        Field({ name: "stock_type", kind: "select", label: _("Stock type"), value: f.stock_type, options: (st.stockTypes || ["AVAILABLE"]).map((t) => ({ value: t, label: _(t) })), onInput: (v) => { f.stock_type = v; persist(); } }));
    } else if (step === "quantity") {
      box.append(Field({ name: "quantity", kind: "qty", label: `${_("Quantity")} · ${f.product}`, value: f.quantity, unit: f.stock_uom, autofocus: true, onInput: (v) => { f.quantity = v; persist(); } }));
    } else if (step === "source") {
      if (f.source_bin && needsCheckDigits(f.source_bin, f.source_hu) && !f.source_checked) {
        box.append(Expect(_("Enter check digits for"), [f.source_bin]),
          Field({ name: "source_check", kind: "scan", label: _("Check digits"), placeholder: _("From the bin's label"), value: f.source_check, autofocus: true,
            onInput: (v) => { f.source_check = v; persist(); },
            onCommit: (v) => verifyCheckDigits(f.source_bin, v, () => { f.source_check = v; f.source_checked = true; go("destination"); }) }),
          Btn({ label: _("Scan a different bin"), small: true, onClick: () => { f.source_bin = ""; f.source_check = ""; persist(); update(); } }));
      } else {
        box.append(Field({ name: "source_bin", kind: "scan", label: _("Source bin"), placeholder: _("Scan bin barcode"), value: f.source_bin, autofocus: true,
          onInput: (v) => { f.source_bin = v; f.source_checked = false; persist(); },
          onCommit: async (v) => {
            const m = await resolve(v, "bin"); if (!m.name) return wrong(v, m, _("a bin"));
            f.source_bin = m.name; persist();
            if (needsCheckDigits(f.source_bin, f.source_hu)) { update(); return; }
            go("destination");
          } }),
          Field({ name: "source_hu", kind: "scan", label: _("Source Handling Unit (optional)"), placeholder: _("Scan HU barcode"), value: f.source_hu,
            onInput: (v) => { f.source_hu = v; persist(); },
            onCommit: async (v) => { const m = await resolve(v, "hu"); if (!m.name) return wrong(v, m, _("a Handling Unit")); f.source_hu = m.name; persist(); } }));
      }
    } else if (step === "destination") {
      if (f.destination_bin && needsCheckDigits(f.destination_bin, f.destination_hu) && !f.destination_checked) {
        box.append(Expect(_("Enter check digits for"), [f.destination_bin]),
          Field({ name: "destination_check", kind: "scan", label: _("Check digits"), placeholder: _("From the bin's label"), value: f.destination_check, autofocus: true,
            onInput: (v) => { f.destination_check = v; persist(); },
            onCommit: (v) => verifyCheckDigits(f.destination_bin, v, () => { f.destination_check = v; f.destination_checked = true; go("review"); }) }),
          Btn({ label: _("Scan a different bin"), small: true, onClick: () => { f.destination_bin = ""; f.destination_check = ""; persist(); update(); } }));
      } else {
        box.append(Field({ name: "destination_bin", kind: "scan", label: _("Destination bin"), placeholder: _("Scan bin barcode"), value: f.destination_bin, autofocus: true,
          onInput: (v) => { f.destination_bin = v; f.destination_checked = false; persist(); },
          onCommit: async (v) => {
            const m = await resolve(v, "bin"); if (!m.name) return wrong(v, m, _("a bin"));
            f.destination_bin = m.name; persist();
            if (needsCheckDigits(f.destination_bin, f.destination_hu)) { update(); return; }
            go("review");
          } }),
          Field({ name: "destination_hu", kind: "scan", label: _("Destination Handling Unit (optional)"), placeholder: _("Scan HU barcode"), value: f.destination_hu,
            onInput: (v) => { f.destination_hu = v; persist(); },
            onCommit: async (v) => { const m = await resolve(v, "hu"); if (!m.name) return wrong(v, m, _("a Handling Unit")); f.destination_hu = m.name; persist(); } }));
      }
    } else {
      box.append(KV([[_("Product"), `${f.product} · ${fmtQty(parseNum(f.quantity))} ${f.stock_uom}`], [_("Stock type"), _(f.stock_type)], [_("From"), f.source_bin + (f.source_hu ? ` / ${f.source_hu}` : "")], [_("To"), f.destination_bin + (f.destination_hu ? ` / ${f.destination_hu}` : "")]]));
    }
    wrap.append(box);
    return wrap;
  },
  actions(ctx) {
    const step = ctx.params.step || "item";
    if (step === "review") return { primary: { label: _("Move"), icon: "✓", run: submit } };
    return { primary: { label: _("Next"), run: () => nextFromButton(step) } };
  },
};

function nextFromButton(step) {
  const f = st.form;
  if (step === "quantity") {
    if (!isNumeric(f.quantity) || parseNum(f.quantity) <= 0) return fail("quantity", _("Enter a quantity greater than zero."));
    f.quantity = fmtQty(parseNum(f.quantity)); return go("source");
  }
  const name = { item: "product",
    source: f.source_bin && needsCheckDigits(f.source_bin, f.source_hu) && !f.source_checked ? "source_check" : "source_bin",
    destination: f.destination_bin && needsCheckDigits(f.destination_bin, f.destination_hu) && !f.destination_checked ? "destination_check" : "destination_bin",
  }[step];
  const rec = S.fields.find((x) => x.name === name);
  if (rec && rec.input.value.trim()) rec.spec.onCommit(rec.input.value.trim()).then((err) => { if (err) fail(name, err); });
  else fail(name, _("Scan the code first."));
}

async function submit() {
  const f = st.form;
  const key = ensureKey(f, "MV");
  persist(true);
  const warehouse = S.resource && S.resource.warehouse;
  const result = await run(() => api("frappe_wms.api.scanner.create_and_confirm_move", {
    warehouse, product: f.product, quantity: parseNum(f.quantity), stock_uom: f.stock_uom, stock_type: f.stock_type,
    source_bin: f.source_bin || undefined, source_hu: f.source_hu || undefined, destination_bin: f.destination_bin, destination_hu: f.destination_hu || undefined,
    scanned_source: f.source_checked ? f.source_check : undefined, scanned_destination: f.destination_checked ? f.destination_check : undefined,
    idempotency_key: key,
  }), { label: _("Moving…"), again: submit });
  if (!result) return;
  feedback.done();
  const msg = _("Moved {0} {1} to {2}", [fmtQty(result.quantity != null ? result.quantity : parseNum(f.quantity)), f.product, f.destination_bin]);
  const w0 = f.w0;
  clearDraft(KEY); st.form = blank(); st.fromDraft = false;
  finishFlow(w0, sectionHash("internal"), msg);
}
